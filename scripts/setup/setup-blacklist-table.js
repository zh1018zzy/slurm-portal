#!/usr/bin/env node

const { createClient } = require('@supabase/supabase-js')
const dotenv = require('dotenv')

// 加载环境变量
dotenv.config({ path: '.env.local' })
dotenv.config({ path: '.env' })

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
)

async function createTableManually() {
  console.log('手动创建 deleted_users_blacklist 表...')
  
  try {
    // 尝试插入一条测试记录来创建表结构
    const { error: insertError } = await supabase
      .from('deleted_users_blacklist')
      .insert([{
        username: 'test_placeholder',
        email: 'test@example.com',
        deleted_by: 'system',
        reason: '表结构测试'
      }])
    
    if (insertError) {
      console.log('表不存在，需要通过SQL创建')
      console.log('请在数据库中执行以下SQL语句:')
      console.log(`
-- 创建黑名单表
CREATE TABLE deleted_users_blacklist (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username character varying(255) UNIQUE NOT NULL,
    email character varying(255),
    deleted_at timestamp with time zone DEFAULT now(),
    deleted_by character varying(255),
    reason text,
    created_at timestamp with time zone DEFAULT now()
);

-- 创建索引
CREATE INDEX idx_deleted_users_blacklist_username ON deleted_users_blacklist(username);
CREATE INDEX idx_deleted_users_blacklist_deleted_at ON deleted_users_blacklist(deleted_at);

-- 启用RLS (Row Level Security)
ALTER TABLE deleted_users_blacklist ENABLE ROW LEVEL SECURITY;

-- 创建策略允许服务角色访问
CREATE POLICY "Enable access for service role" ON deleted_users_blacklist FOR ALL TO service_role;
      `)
      return false
    }
    
    // 删除测试记录
    await supabase
      .from('deleted_users_blacklist')
      .delete()
      .eq('username', 'test_placeholder')
    
    console.log('✅ deleted_users_blacklist 表创建成功并已清理测试数据')
    return true
    
  } catch (error) {
    console.error('操作失败:', error.message)
    return false
  }
}

createTableManually().then(success => {
  if (!success) {
    console.log('\n请联系数据库管理员手动创建表结构，或在 Supabase 控制台的 SQL Editor 中执行上述 SQL 语句')
  }
  process.exit(success ? 0 : 1)
})